// Requires Node.js 25+ (node:module.stripTypeScriptTypes); verified on 25.8.1.
// Host mocks and source-contract checks only. Not ArkTS runtime, device UI, or ReminderAgent acceptance.
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {stripTypeScriptTypes} from 'node:module';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../entry/src/main/ets')+'/';
const read=p=>fs.readFileSync(root+p,'utf8');
let returned;
let reminderFails=false;
let checks=0;
const storage=new Map();
const persistence={focusCommandJson:()=>JSON.stringify(returned),focusStateJson:()=>JSON.stringify(returned),focusTargetStateJson:()=>JSON.stringify(returned)};
const sandbox={KmpPersistenceService:{getInstance:()=>persistence},FocusReminderScheduler:{sync:async()=>{if(reminderFails)throw new Error('permission denied');}},AppLog:{warn:()=>{}},AppStorage:{get:k=>storage.get(k),setOrCreate:(k,v)=>storage.set(k,v)}};
const code=stripTypeScriptTypes(read('common/kmp/KmpFocusTimerRepository.ets').replace(/^import .*;\n/gm,''),{mode:'transform'}).replace(/\bexport /g,'');
vm.createContext(sandbox);
const Repository=vm.runInContext(code+'\nKmpFocusTimerRepository;',sandbox);
const repo=Repository.getInstance();
const expect=(value,expected)=>{assert.deepEqual(value,expected);checks++;};
const state=(uid,timer=null)=>({timer,lastCompletedSession:{uid,taskTitleSnapshot:uid},habitRecordContext:{habitUid:'habit-A',occurredOn:'2026-10-12'},selectedTarget:{kind:'HABIT',uid:'habit-A'},selectedTaskUid:null,selectedTaskTitle:uid,selectedTaskRecentSessions:[],selectedTaskTodayDurationSeconds:15,selectedTaskTotalDurationSeconds:15,error:null,lastOutcome:null});
returned=state('A');
expect((await repo.sessionState('A')).lastCompletedSession.uid,'A');
expect(storage.size,0);
returned=state('B');
const stale=await repo.sessionState('deleted-A');
expect(stale.lastCompletedSession,null);
expect(stale.habitRecordContext,null);
expect(stale.selectedTarget,null);
expect(stale.error,'该专注记录已删除或不可用。');
expect(storage.size,0);
returned=state('B',{sessionUid:'new-B'});
expect((await repo.sessionState('A')).timer.sessionUid,'new-B');
returned={...state('C'),lastOutcome:'APPLIED'};
await repo.execute({operation:'finish'});
expect(storage.get('FocusTimerRevision'),1);
expect(storage.get('KmpDataRevision'),1);
reminderFails=true;
await repo.state();
expect(storage.get('FocusReminderWarning').includes('计时已保存'),true);
const sheet=read('pages/routes/focus/FocusTimerSheet.ets');
const metadata=sheet.slice(sheet.indexOf('  private recordMetadataChanged'),sheet.indexOf('  private beginSavedRecord'));
const RecordCheck=vm.runInContext(stripTypeScriptTypes('class RecordCheck { '+metadata+' }\nRecordCheck;',{mode:'transform'}),sandbox);
const input=new RecordCheck();
input.recordContext={habitUid:'habit-A',occurredOn:'2026-10-12'};
input.expectedHabitUpdatedAt='version-1';
input.state={habitRecordContext:{habitUid:'habit-A',occurredOn:'2026-10-12',habitUpdatedAt:'version-2'}};
expect(input.recordMetadataChanged(),true);
expect(input.expectedHabitUpdatedAt,'version-1');
input.state={habitRecordContext:{habitUid:'habit-A',occurredOn:'2026-10-13',habitUpdatedAt:'version-2'}};
expect(input.recordMetadataChanged(),false);
expect(input.recordContext.occurredOn,'2026-10-12');
const tabs=read('pages/components/AdaptedHdsTabs.ets');
expect(tabs.includes('if (this.hasFocus)'),true);
expect(tabs.includes('this.miniBarExpanded ? HdsBarStyle.EXPAND : HdsBarStyle.COLLAPSE'),true);
expect(tabs.includes('HdsBarLayoutMode.VERTICAL'),false);
console.log('Harmony focus host contract checks: '+checks+' passed. Repository and metadata methods executed with mocked native/reminder APIs; MiniBar checks are source-contract assertions, not device rendering.');
